PRAGMA foreign_keys = ON;
CREATE TABLE IF NOT EXISTS users (
  id INTEGER PRIMARY KEY, login TEXT UNIQUE NOT NULL, name TEXT NOT NULL,
  role TEXT NOT NULL CHECK(role IN ('sales','admin','production','auditor','owner')),
  password TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS items (
  id INTEGER PRIMARY KEY, sku TEXT UNIQUE NOT NULL, name TEXT NOT NULL,
  kind TEXT NOT NULL CHECK(kind IN ('raw','packaging','finished')),
  unit TEXT NOT NULL CHECK(unit IN ('kg','L','piece','packet')),
  reorder INTEGER NOT NULL DEFAULT 0, price INTEGER NOT NULL DEFAULT 0,
  hsn TEXT, gst INTEGER NOT NULL DEFAULT 0, carton INTEGER NOT NULL DEFAULT 1,
  yield INTEGER NOT NULL DEFAULT 0, tolerance INTEGER NOT NULL DEFAULT 300
);
CREATE TABLE IF NOT EXISTS bom (
  product INTEGER NOT NULL REFERENCES items, item INTEGER NOT NULL REFERENCES items,
  quantity INTEGER NOT NULL CHECK(quantity>0), PRIMARY KEY(product,item)
);
CREATE TABLE IF NOT EXISTS parties (
  id INTEGER PRIMARY KEY, name TEXT NOT NULL, kind TEXT NOT NULL,
  state TEXT NOT NULL, code TEXT NOT NULL, gstin TEXT, address TEXT NOT NULL, email TEXT
);
CREATE TABLE IF NOT EXISTS purchases (
  id INTEGER PRIMARY KEY, supplier INTEGER NOT NULL REFERENCES parties, bill TEXT NOT NULL,
  day TEXT NOT NULL, item INTEGER NOT NULL REFERENCES items,
  quantity INTEGER NOT NULL, rate INTEGER NOT NULL, net INTEGER NOT NULL, tax INTEGER NOT NULL,
  UNIQUE(supplier,bill,item)
);
CREATE TABLE IF NOT EXISTS runs (
  id INTEGER PRIMARY KEY, product INTEGER NOT NULL REFERENCES items, day TEXT NOT NULL,
  batches INTEGER NOT NULL, expected INTEGER NOT NULL, output INTEGER NOT NULL,
  note TEXT NOT NULL, tolerance INTEGER NOT NULL, materials INTEGER NOT NULL DEFAULT 0,
  packaging INTEGER NOT NULL DEFAULT 0, labour INTEGER NOT NULL DEFAULT 0,
  utilities INTEGER NOT NULL DEFAULT 0, other INTEGER NOT NULL DEFAULT 0,
  price INTEGER NOT NULL, revision INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS run_lines (
  run INTEGER NOT NULL REFERENCES runs, item INTEGER NOT NULL REFERENCES items,
  planned INTEGER NOT NULL, actual INTEGER NOT NULL, scrap INTEGER NOT NULL,
  value INTEGER NOT NULL, PRIMARY KEY(run,item)
);
CREATE TABLE IF NOT EXISTS orders (
  id INTEGER PRIMARY KEY, customer INTEGER NOT NULL REFERENCES parties,
  salesman INTEGER NOT NULL REFERENCES users, day TEXT NOT NULL, status TEXT NOT NULL,
  token TEXT NOT NULL, UNIQUE(salesman,token)
);
CREATE TABLE IF NOT EXISTS order_lines (
  order_id INTEGER NOT NULL REFERENCES orders, item INTEGER NOT NULL REFERENCES items,
  quantity INTEGER NOT NULL CHECK(quantity>0), price INTEGER NOT NULL CHECK(price>=0),
  PRIMARY KEY(order_id,item)
);
CREATE TABLE IF NOT EXISTS invoices (
  id INTEGER PRIMARY KEY, order_id INTEGER UNIQUE NOT NULL REFERENCES orders, number TEXT UNIQUE NOT NULL,
  day TEXT NOT NULL, due TEXT NOT NULL, customer INTEGER NOT NULL REFERENCES parties,
  name TEXT NOT NULL, gstin TEXT, address TEXT NOT NULL, state TEXT NOT NULL, code TEXT NOT NULL,
  email TEXT, net INTEGER NOT NULL, cgst INTEGER NOT NULL, sgst INTEGER NOT NULL,
  igst INTEGER NOT NULL, total INTEGER NOT NULL, dispatched TEXT
);
CREATE TABLE IF NOT EXISTS invoice_lines (
  invoice INTEGER NOT NULL REFERENCES invoices, item INTEGER NOT NULL REFERENCES items,
  description TEXT NOT NULL, quantity INTEGER NOT NULL, price INTEGER NOT NULL,
  hsn TEXT NOT NULL, rate INTEGER NOT NULL, net INTEGER NOT NULL,
  cgst INTEGER NOT NULL, sgst INTEGER NOT NULL, igst INTEGER NOT NULL,
  PRIMARY KEY(invoice,item)
);
CREATE TABLE IF NOT EXISTS credit_notes (
  id INTEGER PRIMARY KEY, invoice INTEGER UNIQUE NOT NULL REFERENCES invoices,
  number TEXT UNIQUE NOT NULL, day TEXT NOT NULL, reason TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS sequences (
  series TEXT PRIMARY KEY, number INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS payments (
  id INTEGER PRIMARY KEY, invoice INTEGER NOT NULL REFERENCES invoices, day TEXT NOT NULL,
  amount INTEGER NOT NULL CHECK(amount>0), mode TEXT NOT NULL, reference TEXT NOT NULL,
  UNIQUE(invoice,reference)
);
CREATE TABLE IF NOT EXISTS movements (
  id INTEGER PRIMARY KEY, item INTEGER NOT NULL REFERENCES items,
  day TEXT NOT NULL, kind TEXT NOT NULL, source TEXT NOT NULL, quantity INTEGER NOT NULL,
  value INTEGER NOT NULL DEFAULT 0, actor INTEGER NOT NULL REFERENCES users
);
CREATE INDEX IF NOT EXISTS movement_item_day ON movements(item,day,id);
CREATE TABLE IF NOT EXISTS audit (
  id INTEGER PRIMARY KEY, actor INTEGER NOT NULL REFERENCES users,
  at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
  action TEXT NOT NULL, entity TEXT NOT NULL, detail TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS sessions (
  digest TEXT PRIMARY KEY, user INTEGER NOT NULL REFERENCES users, expires INTEGER NOT NULL
);
